#!/usr/bin/env python3
"""Regenerate the internal integrity-hash manifest.

The default mode is read-only and prints the hashes that would be written.
``--autoupdate`` requires confirmation and atomically replaces only
``color_tools/_integrity_hashes.py``.

Requirements: rich
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import hashlib
from pathlib import Path
import re
import sys
from tempfile import NamedTemporaryFile

from rich.console import Console


REPOSITORY_ROOT = Path(__file__).resolve().parent.parent
DATA_DIRECTORY = REPOSITORY_ROOT / "color_tools" / "data"
MANIFEST_PATH = REPOSITORY_ROOT / "color_tools" / "_integrity_hashes.py"
_SHA256_PATTERN = re.compile(r"^[0-9a-f]{64}$")

if str(REPOSITORY_ROOT) not in sys.path:
    sys.path.insert(0, str(REPOSITORY_ROOT))

from color_tools.constants import ColorConstants  # noqa: E402


CORE_DATA_FILENAMES = (
    ColorConstants.COLORS_JSON_FILENAME,
    ColorConstants.FILAMENTS_JSON_FILENAME,
    ColorConstants.MAKER_SYNONYMS_JSON_FILENAME,
)
console = Console()


@dataclass(frozen=True)
class IntegrityManifest:
    """All generated integrity values written to the internal manifest."""

    core_data_hashes: dict[str, str]
    system_palette_hashes: dict[str, str]
    matrices_expected_hash: str
    color_constants_expected_hash: str


def print_section(title: str) -> None:
    """Print a section header."""
    console.print(f"\n[bold cyan]{title}[/bold cyan]")


def print_hash(name: str, hash_value: str) -> None:
    """Print one labeled hash."""
    console.print(f'[green]{name}[/green] = "[yellow]{hash_value}[/yellow]"')


def print_error(message: str) -> None:
    """Print an error message."""
    console.print(f"[bold red]ERROR:[/bold red] {message}")


def print_success(message: str) -> None:
    """Print a success message."""
    console.print(f"[bold green][OK][/bold green] {message}")


def print_info(message: str) -> None:
    """Print secondary information."""
    console.print(f"[dim]{message}[/dim]")


def compute_file_hash(filepath: Path) -> str | None:
    """Return a normalized SHA-256 digest, or None for a missing file."""
    if not filepath.is_file():
        return None
    content = filepath.read_bytes().replace(b"\r\n", b"\n")
    return hashlib.sha256(content).hexdigest()


def _require_file_hash(filepath: Path) -> str:
    """Return a file hash or raise a focused missing-file error."""
    hash_value = compute_file_hash(filepath)
    if hash_value is None:
        raise FileNotFoundError(f"Protected data file not found: {filepath}")
    return hash_value


def collect_integrity_manifest(
    *,
    data_directory: Path = DATA_DIRECTORY,
) -> IntegrityManifest:
    """Calculate every protected hash from the current repository contents."""
    core_hashes = {
        filename: _require_file_hash(data_directory / filename)
        for filename in CORE_DATA_FILENAMES
    }
    palette_directory = data_directory / "palettes"
    palette_files = sorted(palette_directory.glob("*.json"))
    if not palette_files:
        raise FileNotFoundError(
            f"No system palette JSON files found in: {palette_directory}"
        )
    palette_hashes = {
        path.name: _require_file_hash(path)
        for path in palette_files
    }
    return IntegrityManifest(
        core_data_hashes=core_hashes,
        system_palette_hashes=palette_hashes,
        matrices_expected_hash=ColorConstants._compute_matrices_hash(),
        color_constants_expected_hash=ColorConstants._compute_hash(),
    )


def _render_hash_mapping(name: str, values: dict[str, str]) -> list[str]:
    """Render one sorted, typed Python hash mapping."""
    lines = [f"{name}: dict[str, str] = {{"]
    lines.extend(
        f'    "{filename}": "{values[filename]}",'
        for filename in sorted(values)
    )
    lines.append("}")
    return lines


def render_integrity_manifest(manifest: IntegrityManifest) -> str:
    """Render a deterministic Python module containing only generated data."""
    lines = [
        '"""Generated integrity hashes for protected Color Tools data.',
        "",
        "Do not edit this file manually. Regenerate it with",
        "``python tooling/update_hashes.py --autoupdate``.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "",
    ]
    lines.extend(_render_hash_mapping("CORE_DATA_HASHES", manifest.core_data_hashes))
    lines.append("")
    lines.extend(
        _render_hash_mapping(
            "SYSTEM_PALETTE_HASHES",
            manifest.system_palette_hashes,
        )
    )
    lines.extend(
        (
            "",
            f'MATRICES_EXPECTED_HASH: str = "{manifest.matrices_expected_hash}"',
            (
                'COLOR_CONSTANTS_EXPECTED_HASH: str = '
                f'"{manifest.color_constants_expected_hash}"'
            ),
            "",
        )
    )
    return "\n".join(lines)


def write_integrity_manifest(
    manifest: IntegrityManifest,
    output_path: Path = MANIFEST_PATH,
) -> Path:
    """Atomically replace the generated manifest and return its path."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    rendered = render_integrity_manifest(manifest)
    temporary_path: Path | None = None
    try:
        with NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            dir=output_path.parent,
            prefix=f".{output_path.name}.",
            suffix=".tmp",
            delete=False,
        ) as temporary_file:
            temporary_file.write(rendered)
            temporary_path = Path(temporary_file.name)
        temporary_path.replace(output_path)
    finally:
        if temporary_path is not None and temporary_path.exists():
            temporary_path.unlink()
    return output_path


def _print_manifest(manifest: IntegrityManifest) -> None:
    """Display every value in a generated manifest."""
    print_section("MAIN DATA FILE HASHES")
    for filename, hash_value in manifest.core_data_hashes.items():
        print_hash(filename, hash_value)

    print_section("SYSTEM PALETTE HASHES")
    for filename, hash_value in manifest.system_palette_hashes.items():
        print_hash(filename, hash_value)
    print_info(f"Found {len(manifest.system_palette_hashes)} palette files")

    print_section("TRANSFORMATION MATRICES HASH")
    print_hash("MATRICES_EXPECTED_HASH", manifest.matrices_expected_hash)
    print_section("COLOR CONSTANTS HASH")
    print_hash("COLOR_CONSTANTS_EXPECTED_HASH", manifest.color_constants_expected_hash)


def _validate_manifest(manifest: IntegrityManifest) -> None:
    """Reject incomplete or malformed generated values before writing."""
    expected_core = set(CORE_DATA_FILENAMES)
    if set(manifest.core_data_hashes) != expected_core:
        raise ValueError("Integrity manifest does not contain every core data file")
    if not manifest.system_palette_hashes:
        raise ValueError("Integrity manifest does not contain any system palettes")
    all_hashes = (
        *manifest.core_data_hashes.values(),
        *manifest.system_palette_hashes.values(),
        manifest.matrices_expected_hash,
        manifest.color_constants_expected_hash,
    )
    if not all(_SHA256_PATTERN.fullmatch(value) for value in all_hashes):
        raise ValueError("Integrity manifest contains an invalid SHA-256 digest")


def _parse_args() -> argparse.Namespace:
    """Parse command-line options."""
    parser = argparse.ArgumentParser(
        description="Regenerate the Color Tools integrity-hash manifest"
    )
    parser.add_argument(
        "--autoupdate",
        action="store_true",
        help="Atomically update the generated manifest after confirmation",
    )
    parser.add_argument(
        "--constants-only",
        action="store_true",
        help="Only calculate and show the ColorConstants hash",
    )
    parser.add_argument(
        "--filaments-only",
        action="store_true",
        help="Only calculate and show the filaments.json hash",
    )
    parser.add_argument(
        "--palettes-only",
        action="store_true",
        help="Only calculate and show all discovered system palette hashes",
    )
    return parser.parse_args()


def main() -> None:
    """Print or safely regenerate integrity hashes."""
    args = _parse_args()
    console.print("[bold blue]Color Tools - Hash Update Utility[/bold blue]")
    console.print("=" * 40)

    if args.constants_only:
        print_section("COLOR CONSTANTS HASH")
        print_hash("COLOR_CONSTANTS_EXPECTED_HASH", ColorConstants._compute_hash())
        return
    if args.filaments_only:
        print_section("FILAMENTS.JSON HASH")
        print_hash("filaments.json", _require_file_hash(DATA_DIRECTORY / "filaments.json"))
        return
    if args.palettes_only:
        manifest = collect_integrity_manifest()
        print_section("SYSTEM PALETTE HASHES")
        for filename, hash_value in manifest.system_palette_hashes.items():
            print_hash(filename, hash_value)
        return

    try:
        manifest = collect_integrity_manifest()
        _validate_manifest(manifest)
    except (FileNotFoundError, ValueError) as error:
        print_error(str(error))
        raise SystemExit(1) from error

    _print_manifest(manifest)
    if not args.autoupdate:
        print_info("Read-only mode: no files were modified.")
        print_info("Run with --autoupdate to replace the generated manifest.")
        return

    response = input(
        "Do you want to replace color_tools/_integrity_hashes.py? (y/N): "
    )
    if response.casefold() not in {"y", "yes"}:
        console.print("[bold red]Cancelled.[/bold red] No files were modified.")
        return

    output_path = write_integrity_manifest(manifest)
    print_success(f"Updated {output_path}")
    console.print("\n[bold cyan]Final verification:[/bold cyan]")
    console.print("   [yellow]python -m color_tools --verify-all[/yellow]")


if __name__ == "__main__":
    main()
